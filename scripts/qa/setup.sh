#!/usr/bin/env bash
set -euo pipefail

QA_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$QA_ROOT"
source "$QA_ROOT/scripts/qa/common.sh"
qa_private_dir "$QA_ROOT/.qa-private"

[[ ! -L .env.qa ]] || { echo "Refusing to use .env.qa when it is a symbolic link." >&2; exit 1; }

if [[ ! -f .env.qa ]]; then
  system_python="$(qa_system_python)" || { echo "Falta Python 3.12 o superior." >&2; exit 1; }
  umask 077
  project_id="$("$system_python" -c 'import secrets; print(secrets.token_hex(4))')"
  db_port="$(qa_find_db_port)"
  django_key="$("$system_python" -c 'import secrets; print(secrets.token_urlsafe(48))')"
  db_password="$("$system_python" -c 'import secrets; print(secrets.token_urlsafe(32))')"
  cat > .env.qa <<EOF
# Local-only QA configuration; generated by scripts/qa/setup.sh.
QA_PROJECT_NAME=beatscloud-qa-${project_id}
DJANGO_SECRET_KEY=${django_key}
DJANGO_DEBUG=True
DJANGO_ALLOWED_HOSTS=127.0.0.1,localhost
DJANGO_CSRF_TRUSTED_ORIGINS=http://127.0.0.1:3010,http://localhost:3010,http://localhost:3000
FRONTEND_URL=http://127.0.0.1:3010
DB_ENGINE=django.db.backends.postgresql
DB_NAME=beatscloud_qa_local
DB_USER=beatscloud_qa
DB_PASSWORD=${db_password}
DB_HOST=127.0.0.1
DB_PORT=${db_port}
QA_BACKEND_PORT=8010
QA_FRONTEND_PORT=3010
MEDIA_ROOT=media/qa
FFMPEG_PATH=ffmpeg
R2_ACCOUNT_ID=
R2_ACCESS_KEY_ID=
R2_SECRET_ACCESS_KEY=
R2_BUCKET_NAME=
R2_UPLOADS_ENABLED=false
TRANSBANK_COMMERCE_CODE=
TRANSBANK_API_KEY=
TRANSBANK_INTEGRATION_TYPE=TEST
EMAIL_BACKEND=django.core.mail.backends.console.EmailBackend
EMAIL_HOST_USER=
EMAIL_HOST_PASSWORD=
RESEND_API_KEY=
GMAIL_OAUTH_TOKEN_JSON=
EOF
  qa_secure_file .env.qa
else
  [[ ! -L .env.qa ]] || { echo "Refusing to use .env.qa when it is a symbolic link." >&2; exit 1; }
  qa_secure_file .env.qa
  echo ".env.qa exists; preserving it and validating its QA-only settings."
fi

qa_load_env
qa_select_compose

venv_python="$(qa_venv_python_path)"
if [[ ! -x "$venv_python" ]]; then
  "$(qa_system_python)" -m venv .venv
fi
qa_python -m pip install -r requirements.txt

if [[ ! -f frontend/client/node_modules/vite/bin/vite.js ]]; then
  (cd frontend/client && npm ci)
else
  (cd frontend/client && npm ls --depth=0 >/dev/null 2>&1) || (cd frontend/client && npm ci)
fi

if [[ -d "$MEDIA_ROOT" && ! -f "$MEDIA_ROOT/.beatscloud-qa-media" ]]; then
  echo "Refusing to reuse media/qa because its QA sentinel is absent." >&2
  exit 1
fi
mkdir -p "$MEDIA_ROOT"
touch "$MEDIA_ROOT/.beatscloud-qa-media"
chmod 600 "$MEDIA_ROOT/.beatscloud-qa-media"

qa_compose up -d db
ready=0
for _ in $(seq 1 60); do
  if qa_compose exec -T db pg_isready -U "$DB_USER" -d "$DB_NAME" >/dev/null 2>&1; then
    ready=1
    break
  fi
  sleep 2
done
[[ "$ready" == 1 ]] || { echo "QA PostgreSQL did not become ready." >&2; exit 1; }

qa_python manage.py migrate --noinput
qa_python manage.py prepare_demo_catalog
qa_python manage.py prepare_qa_users
qa_python manage.py generate_qa_catalog --count 120 --seed 20261118

echo "QA setup complete. Start services with scripts/qa/start.sh."
echo "QA environment file is local and mode 0600: .env.qa"
